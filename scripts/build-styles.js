import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../frontend/discourse-appearance");
const files = JSON.parse(readFileSync(resolve(root, "styles.json"), "utf8"));
if (!Array.isArray(files) || !files.length || new Set(files).size !== files.length) {
  throw new Error("Expected an ordered, nonempty stylesheet manifest without duplicates");
}
const source = "// Generated by npm run build:styles. Edit styles/ and styles.json instead.\n" + files.map(file => {
  if (!/^styles\/[a-z0-9-]+\.scss$/.test(file)) throw new Error(`Invalid stylesheet path: ${file}`);
  return readFileSync(resolve(root, file), "utf8");
}).join("\n");
const output = resolve(root, "common.scss");
if (process.argv.includes("--check")) {
  if (readFileSync(output, "utf8") !== source) {
    throw new Error("Generated common.scss is stale. Run npm run build:styles and commit its output.");
  }
} else {
  writeFileSync(output, source);
}
