#!/usr/bin/env bash
# Operator-installed, staging-only entry point. No production bucket or credentials.
set -euo pipefail
sha="${1:?source revision required}"
digest="${2:?archive checksum required}"
run="${3:?workflow run-attempt required}"
[[ "$sha" =~ ^[0-9a-f]{40}$ && "$digest" =~ ^[0-9a-f]{64}$ && "$run" =~ ^[0-9]{1,20}-[0-9]{1,5}$ ]] || exit 2
test -f /var/lib/svdex/staging-host
source /etc/svdex-aws.env
export AWS_DEFAULT_REGION
account=$(aws sts get-caller-identity --query Account --output text)
bucket="svdex-staging-$account-$AWS_DEFAULT_REGION"
umask 077
work=$(mktemp -d /var/lib/svdex/staging-release.XXXXXX)
log="/var/log/svdex-staging-$run.log"
install -m 600 /dev/null "$log"
status=failed
phase=lock
receipt() {
  code=$?
  trap - EXIT
  python3 - "$sha" "$run" "$status" "$phase" "$work/receipt.json" <<'PY'
import datetime,json,sys
sha,run,status,phase,path=sys.argv[1:]
with open(path,'w') as out:
    manifest_path=__import__('pathlib').Path(path).parent/'manifest.json'
    manifest=json.load(open(manifest_path)) if manifest_path.exists() else {}
    json.dump(dict(source_commit=sha,source_tree=manifest.get('source_tree'),hostname='staging.svdex.com',run_id=run,status=status,phase=phase,finished_at=datetime.datetime.now(datetime.timezone.utc).isoformat()),out)
PY
  if [[ "$status" == success ]]; then
    if ! aws s3 cp "$work/receipt.json" "s3://$bucket/deployments/verified.json" --sse AES256 --only-show-errors; then
      status=failed; phase=publish; code=1
      python3 - "$work/receipt.json" <<'PY'
import json,sys
path=sys.argv[1]; data=json.load(open(path));data.update(status='failed',phase='publish')
with open(path,'w') as out: json.dump(data,out)
PY
    fi
  fi
  aws s3 cp "$work/receipt.json" "s3://$bucket/deployments/github/$run.json" --sse AES256 --only-show-errors || true
  echo "SVDEX staging $sha: $status ($phase)."
  exit "$code"
}
trap receipt EXIT
exec 9>/run/svdex-staging-deploy.lock
flock -n 9 || exit 1
phase=download
aws s3 cp "s3://$bucket/releases/github/$run/release.tar.gz" "$work/release.tar.gz" --only-show-errors >>"$log" 2>&1
printf '%s  %s\n' "$digest" "$work/release.tar.gz" | sha256sum -c - >>"$log" 2>&1
python3 - "$work/release.tar.gz" "$sha" <<'PY' >>"$log" 2>&1
import json,sys,tarfile
with tarfile.open(sys.argv[1]) as archive:
    entry=next(m for m in archive.getmembers() if m.name in ('manifest.json','./manifest.json'))
    manifest=json.load(archive.extractfile(entry))
if manifest['release_kind']!='staging' or manifest['hostname']!='staging.svdex.com': raise ValueError('Staging bundle required')
if manifest['source_commit']!=sys.argv[2] or manifest['source_dirty']: raise ValueError('Unexpected revision')
PY
tar -xzf "$work/release.tar.gz" -C "$work"
shared=/var/discourse/shared/standalone/svdex-release
mkdir -p "$shared"
chmod 755 /var/discourse/shared /var/discourse/shared/standalone
install -d -m 755 /var/discourse/shared/standalone/log/var-log
cp -a "$work/." "$shared/"
bash "$work/aws/replace-theme-sources.sh" "$work" "$shared"
phase=build
# Build a complete staging container configuration from credential-free code.
# Every environment value is fixed here; production configuration is never read.
python3 - "$work" <<'PY' >>"$log" 2>&1
import base64,json,pathlib
root=pathlib.Path(__import__('sys').argv[1]); m=json.loads((root/'manifest.json').read_text())
# app.yml is YAML generated by Ruby. Reuse its exact plugin payload through a
# separate JSON extraction in the runner package, not a production app export.
payload=(root/'staging-plugin.b64').read_text().strip()
env={'LANG':'en_US.UTF-8','LC_ALL':'en_US.UTF-8','DISCOURSE_HOSTNAME':'staging.svdex.com',
 'DISCOURSE_DEVELOPER_EMAILS':'owner@staging.svdex.com','DISCOURSE_NOTIFICATION_EMAIL':'notifications@staging.svdex.com',
 'DISCOURSE_FORCE_HTTPS':True,'DISCOURSE_LOGIN_REQUIRED':True,'DISCOURSE_ALLOW_NEW_REGISTRATIONS':False,
 'DISCOURSE_DISABLE_EMAILS':'yes','DISCOURSE_ENABLE_GOOGLE_OAUTH2_LOGINS':False,
 'DISCOURSE_TITLE':'SVDEX','LETSENCRYPT_ACCOUNT_EMAIL':'owner@staging.svdex.com'}
app={'templates':['templates/'+n+'.template.yml' for n in ['postgres','redis','web','web.ratelimited','web.ssl','web.letsencrypt.ssl']],
 'expose':['80:80','443:443'],'params':{'version':m['discourse_revision']},'env':env,
 'volumes':[{'volume':{'host':'/var/discourse/shared/standalone','guest':'/shared'}},{'volume':{'host':'/var/discourse/shared/standalone/log/var-log','guest':'/var/log'}}],
 'hooks':{'after_code':[{'file':{'path':'/tmp/svdex-plugin.tar.gz.b64','contents':payload,'chmod':'600'}},
 {'exec':{'cmd':['base64 --decode /tmp/svdex-plugin.tar.gz.b64 | tar -xz -C /var/www/discourse/plugins','chown -R discourse:www-data /var/www/discourse/plugins/discourse-svdex','rm /tmp/svdex-plugin.tar.gz.b64']}}]}}
# JSON is valid YAML and avoids a host-side YAML dependency.
path=pathlib.Path('/var/discourse/containers/app.yml');path.write_text(json.dumps(app,indent=2)+'\n');path.chmod(0o600)
PY
cd /var/discourse
expected_docker=$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1]))["docker_revision"])' "$work/manifest.json")
test "$(git rev-parse HEAD)" = "$expected_docker"
(umask 022; ./launcher rebuild app </dev/null) >>"$log" 2>&1
find "$shared" -type d -exec chmod 755 {} +
find "$shared" -type f ! -name app.yml -exec chmod 644 {} +
phase=ready
# Launcher returns before Redis/PostgreSQL/Rails have necessarily started.
# HTTPS health must succeed before a Rails runner tries its first connection.
curl -fsS --retry 30 --retry-all-errors --retry-delay 5 --max-time 10 https://staging.svdex.com/srv/status >>"$log" 2>&1
phase=configure
aws ssm get-parameter --name /svdex/staging/admin-password --with-decryption --query Parameter.Value --output text > "$work/admin-password"
cat "$work/admin-password" | docker exec -i -u discourse -e SVDEX_STAGING_SETUP=1 app bash -lc \
  'cd /var/www/discourse && bundle exec rails runner /shared/svdex-release/configure-staging.rb' >>"$log" 2>&1
rm -f "$work/admin-password"
phase=verify
curl -fsS --retry 6 --retry-delay 10 --max-time 20 https://staging.svdex.com/srv/status >>"$log" 2>&1
docker exec -u discourse app bash -lc 'cd /var/www/discourse && bundle exec rails runner '\''
  raise "Wrong host" unless GlobalSetting.hostname == "staging.svdex.com"
  raise "Email enabled" unless SiteSetting.disable_emails == "yes"
  raise "Access open" unless SiteSetting.login_required && !SiteSetting.allow_new_registrations
  raise "External form enabled" unless SiteSetting.svdex_private_access_form_url.blank?
  raise "Missing theme" unless Theme.find(SiteSetting.default_theme_id).name == "SVDEX"
  raise "Missing content" unless Group.find_by!(name: "companies").users.count >= 2
  puts "Staging isolation and native content verified."
'\''' >>"$log" 2>&1
status=success
phase=complete
